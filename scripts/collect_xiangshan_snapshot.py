#!/usr/bin/env python3
"""Collect an immutable XiangShan snapshot without inheriting old validation claims."""
import argparse
import datetime
import gzip
import hashlib
import json
from pathlib import Path
import re
import shutil

p=argparse.ArgumentParser()
p.add_argument('artifacts',type=Path)
p.add_argument('destination',type=Path)
p.add_argument('config',choices=['MinimalConfig','DefaultConfig'])
a=p.parse_args()
source=a.artifacts/a.config
assert (source/'SUCCESS').is_file()
assert (source/'lint.exit').read_text().strip()=='0'
out=a.destination/a.config
assert not out.exists(), f'Refusing to overwrite {out}'
(out/'rtl').mkdir(parents=True)
(out/'flat').mkdir()
(out/'meta').mkdir()
rtl=source/'rtl'
files=sorted(f for f in rtl.iterdir() if f.suffix in ('.sv','.v','.svh','.vh'))
hashes={}
for f in files:
    shutil.copyfile(f,out/'rtl'/f.name)
    hashes[f.name]=hashlib.sha256(f.read_bytes()).hexdigest()
hdl=[f for f in files if f.suffix in ('.sv','.v')]
(out/'files.f').write_text('+incdir+rtl\n'+''.join(f'rtl/{f.name}\n' for f in hdl))
if (rtl/'filelist.f').exists():
    shutil.copyfile(rtl/'filelist.f',out/'filelist.f')
if (rtl/'.__diff__').exists():
    shutil.copyfile(rtl/'.__diff__',out/'meta/git-provenance.txt')
for name in ('source-status.txt','submodules.txt','source-commit.txt','java-version.txt','mill-version.txt'):
    shutil.copyfile(a.artifacts/name,out/'meta'/name)
shutil.copyfile(source/'lint.log',out/'meta/verilator-lint.log')
(out/'meta/rtl-sha256.json').write_text(json.dumps(hashes,indent=2)+'\n')
flat=out/'flat'/f'{a.config}.flat.sv.gz'
modules=0
with flat.open('wb') as raw, gzip.GzipFile(fileobj=raw,mode='wb',mtime=0) as z:
    z.write(b'// Frozen XiangShan kunminghu-v3 aa6b52033add528a504bdb2c2b726100d89f070a\n')
    for f in hdl:
        data=f.read_bytes()
        modules+=len(re.findall(rb'^module\s',data,re.M))
        z.write(f'\n// Source: {f.name}\n'.encode()+data+b'\n')
firtool=(rtl/'XSTop.sv').read_text().split('Generated by CIRCT firtool-',1)[1].splitlines()[0].strip()
manifest={
    'design':'xiangshan','config':a.config,'top_module':'XSTop',
    'generator':{'repo':'https://github.com/OpenXiangShan/XiangShan','branch':'kunminghu-v3',
      'commit':'aa6b52033add528a504bdb2c2b726100d89f070a','commit_date':'2026-09-24T14:23:39+08:00'},
    'toolchain':{'firtool':firtool,'chisel':'7.13.0','scala':'2.13.17','mill':'0.12.17','jdk':'Eclipse Temurin 21.0.8+9'},
    'build_command':f'make verilog CONFIG={a.config} BUILD_DIR=<isolated-build-directory> JVM_XMX=64G JVM_XSS=256m',
    'frozen_on':datetime.datetime.now(datetime.timezone.utc).isoformat(),
    'contents':{'rtl_files':len(files),'modules':modules,'files.f':'Complete portable HDL file list','filelist.f':'Original generator file list',
       'rtl_hashes':'meta/rtl-sha256.json','submodule_commits':'meta/submodules.txt','flat_sha256':hashlib.sha256(flat.read_bytes()).hexdigest()},
    'validation':{'elaboration':'PASS','source_dirty':bool((a.artifacts/'source-status.txt').read_text().strip()),
      'lint':{'status':'PASS','version':'Verilator 5.052 2026-09-05','command':'verilator --lint-only --timing -Wno-fatal --top-module XSTop -f files.f',
        'errors':0,'warnings_nonfatal':True,'log':'meta/verilator-lint.log'},
      'simulation':{'status':'NOT RUN','note':'Historical CoreMark results apply only to the July 2026 SimTop snapshot.'}},
    'notes':['Stock FPGA-platform XSTop; behavioral SRAM models.',
      'The complete files.f includes every emitted HDL file. The original filelist.f is retained for provenance.',
      'FIRRTL is omitted because of its size. The standalone flattened HDL is gzip-compressed.',
      'No whole-core formal verification claim. Leaf-module checks are described separately.']
}
(out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps({'config':a.config,'files':len(files),'modules':modules,'output':str(out)}))
